def hx(s, a=255):
    s = s.lstrip("#")
    r, g, b = int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16)
    return (r, g, b, a)

def rounded(w, h, radius, fill, outline=None, ow=2, glow=None, glow_r=10):
    canvas = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    if glow:
        gimg = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        gd = ImageDraw.Draw(gimg)
        gd.rounded_rectangle([2, 2, w - 3, h - 3], radius=radius + 2, fill=glow)
        gimg = gimg.filter(ImageFilter.GaussianBlur(glow_r))
        canvas = Image.alpha_composite(canvas, gimg)
    d = ImageDraw.Draw(canvas)
    inset = max(ow, 2)
    d.rounded_rectangle([inset, inset, w - inset - 1, h - inset - 1], radius=radius, fill=fill, outline=outline, width=ow)
    return canvas

def save(name, img):
    path = OUT / (name + ".png")
    img.save(path)
    print(path.name, img.size)

